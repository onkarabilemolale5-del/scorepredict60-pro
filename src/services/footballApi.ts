/**
 * Fetch live data from football-data.org API if user configured API key
 */
export async function fetchLiveFootballDataMatches(apiKey: string): Promise<MatchFixture[] | null> {
  try {
    const res = await fetch('https://api.football-data.org/v4/matches', {
      headers: {
        'X-Auth-Token': apiKey,
      },
    });

    if (!res.ok) {
      throw new Error(`API returned status ${res.status}`);
    }

    const data = await res.json();
    if (data.matches && data.matches.length > 0) {
      // Parse matches and enrich with prediction engine
      return data.matches.map((m: any, idx: number) => {
        const homeTeam = m.homeTeam?.name || 'Home Team';
        const awayTeam = m.awayTeam?.name || 'Away Team';
        const leagueCode = m.competition?.code as LeagueId;

        const defaultInjuries = [
          { player: 'Starting Defender', team: 'away' as const, position: 'DEF' as const, reason: 'Muscle strain', status: 'Doubtful' as const, importance: 2 as const }
        ];

        const defaultRef = {
          name: m.referees?.[0]?.name || 'Slavko Vincic (FIFA)',
          matchesOfficiated: 14,
          avgYellowCardsPerGame: 4.3,
          avgRedCardsPerGame: 0.18,
          penaltiesAwardedPerGame: 0.35,
          strictness: 'Average' as const,
        };

        const prediction = calculateMatchPrediction({
          homeTeam,
          awayTeam,
          homeForm: [
            { opponent: 'Recent Match', result: 'W' as const, score: '2-1', isHome: true, date: 'Recent' },
            { opponent: 'Recent Match', result: 'D' as const, score: '1-1', isHome: false, date: 'Recent' },
            { opponent: 'Recent Match', result: 'W' as const, score: '1-0', isHome: true, date: 'Recent' },
          ],
          awayForm: [
            { opponent: 'Recent Match', result: 'D' as const, score: '0-0', isHome: false, date: 'Recent' },
            { opponent: 'Recent Match', result: 'W' as const, score: '2-1', isHome: true, date: 'Recent' },
            { opponent: 'Recent Match', result: 'L' as const, score: '1-2', isHome: false, date: 'Recent' },
          ],
          h2h: [],
          injuries: defaultInjuries,
          referee: defaultRef,
        });

        return {
          id: String(m.id || `api-${idx}`),
          leagueId: leagueCode || 'PL',
          leagueName: m.competition?.name || 'Top League',
          leagueLogo: m.competition?.emblem || 'https://crests.football-data.org/PL.png',
          homeTeam,
          homeLogo: m.homeTeam?.crest || 'https://crests.football-data.org/57.png',
          awayTeam,
          awayLogo: m.awayTeam?.crest || 'https://crests.football-data.org/61.png',
          utcDate: m.utcDate,
          venue: 'Host Stadium',
          status: m.status === 'IN_PLAY' ? 'LIVE' : m.status === 'FINISHED' ? 'FINISHED' : 'TIMED',
          currentScore: m.score?.fullTime?.home !== null ? { home: m.score.fullTime.home, away: m.score.fullTime.away } : undefined,
          homeForm: [],
          awayForm: [],
          h2h: [],
          injuries: defaultInjuries,
          referee: defaultRef,
          homeLineup: {
            formation: '4-3-3',
            startingXI: [],
            dangerMan: 'Top Goalscorer',
          },
          awayLineup: {
            formation: '4-2-3-1',
            startingXI: [],
            dangerMan: 'Key Forward',
          },
          prediction,
        };
      });
    }
    return null;
  } catch (err) {
    console.warn('football-data.org fetch error, falling back to cached intelligence:', err);
    return null;
  }
}
