// Helper to generate dynamic ISO dates for Today & Tomorrow in Africa/Gaborone
function getDynamicMatchDate(isTomorrow: boolean, hour: number, minute: number): string {
  const d = new Date();
  if (isTomorrow) {
    d.setDate(d.getDate() + 1);
  }
  // Gaborone is UTC+2, so UTC hour = Gaborone hour - 2
  const utcHour = (hour - 2 + 24) % 24;
  d.setUTCHours(utcHour, minute, 0, 0);
  return d.toISOString();
}

